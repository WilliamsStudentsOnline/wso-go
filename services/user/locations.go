func canonicalUSState(value string) (string, bool) {
	trimmed := strings.TrimSpace(value)
	if state, ok := stateAbbreviations[strings.ToUpper(trimmed)]; ok {
		return state, true
	}
	for _, state := range validStates {
		if strings.EqualFold(trimmed, state) {
			return state, true
		}
	}
	return "", false
}

var stateCodesByName = func() map[string]string {
	codes := make(map[string]string, len(stateAbbreviations))
	for code, name := range stateAbbreviations {
		codes[strings.ToLower(name)] = code
	}
	return codes
}()

